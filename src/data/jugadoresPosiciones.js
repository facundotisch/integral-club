export function obtenerPosicionesJugador(playerName, sesiones = []) {
  if (!playerName || !String(playerName).trim()) return '—';

  const clean = String(playerName).trim();
  if (POSICIONES_SHEET[clean]) {
    return POSICIONES_SHEET[clean];
  }

  for (const [key, pos] of Object.entries(POSICIONES_SHEET)) {
    if (key.toLowerCase() === clean.toLowerCase()) {
      return pos;
    }
  }

  if (Array.isArray(sesiones)) {
    for (const s of sesiones) {
      if (s.jugadores) {
        for (const j of s.jugadores) {
          if (j.jugador === clean || (j.jugador && j.jugador.toLowerCase() === clean.toLowerCase())) {
            const raw = String(j.pos || '').trim().toUpperCase();
            if (POS_MAP_ABBR[raw]) return POS_MAP_ABBR[raw];
            if (raw) return raw;
          }
        }
      }
    }
  }

  return '—';
}

